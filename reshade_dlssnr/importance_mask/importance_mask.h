#pragma once

#include <cstdint>

#include <d3d12.h>
#include <wrl/client.h>

#include "command_context.h"
#include "compute_engine.h"
#include "importance_mask/settings.h"

namespace reshade_dlssnr {

enum class PipelineNodeId : uint32_t;
struct PipelineStepDef;

class ImportanceMask {
 public:
  struct Output {
    ID3D12Resource* mask = nullptr;
    unsigned int width = 0;
    unsigned int height = 0;
    bool valid = false;
  };

  void Shutdown();

  // Publishes the most recently completed mask for use in the next frame.
  // Call once at Present, after all Pre/Post-DLSS passes for the frame.
  void AdvanceFrame(bool enabled);

  // The frame snapshot is immutable through the current frame, even if a new
  // mask is generated by the first Pre/Post-DLSS pass during that frame.
  Output GetFrameOutput() const;
  Output GetGeneratedOutput() const;
  bool CanBuildThisFrame() const { return !built_this_frame_; }

  bool Build(CommandContext& command,
             ComputeEngine& codec,
             ID3D12GraphicsCommandList* command_list,
             ID3D12Device* device,
             ID3D12Resource* model_input,
             ID3D12Resource* model_output,
             const ImportanceMaskSettings& settings);

 private:
  bool EnsureResources(ID3D12Device* device,
                       unsigned int width,
                       unsigned int height,
                       uint32_t destination_index);

  Microsoft::WRL::ComPtr<ID3D12Resource> masks_[2];
  uint32_t frame_index_ = 0;
  uint32_t latest_index_ = 0;
  unsigned int mask_width_[2] = {};
  unsigned int mask_height_[2] = {};
  bool frame_valid_ = false;
  bool latest_valid_ = false;
  bool built_this_frame_ = false;
  bool generated_this_frame_ = false;
};

const PipelineStepDef* ImportanceMaskStepFor(PipelineNodeId id);

}  // namespace reshade_dlssnr
