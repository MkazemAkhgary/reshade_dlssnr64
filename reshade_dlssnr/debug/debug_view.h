// Debug views: display pipeline resources by role.
//
// This module is a pure observer — it reads what the pipeline already
// produced, and never recomputes anything. The pipeline populates a
// DebugSnapshot (raw pointers to its live resources) as it runs. If the
// pipeline changes (e.g. a new stage is added), the snapshot reflects it
// automatically because it holds role-to-resource mappings, not copies.
//
// Adding or removing a view = editing one table entry in debug_view.cpp.
#pragma once

#include <d3d12.h>

#include <cstdint>

#include "gpu/command_context.h"
#include "gpu/compute_engine.h"
#include "gpu/pass_resources.h"
#include "grade/settings.h"
#include "model/model_input.h"

namespace reshade_dlssnr {

// Pointers captured during a pass. Only raw pointers are held; the caller
// guarantees the resources stay alive until the pass finishes.
struct DebugSnapshot {
  // Model input before any post-processing (source frame or DLSS output).
  ID3D12Resource* source = nullptr;
  unsigned int source_width = 0;
  unsigned int source_height = 0;

  // Latest asynchronously read game exposure value.
  bool game_exposure_available = false;
  float game_exposure = 1.0f;

  // Model input after HDR normalization and optional resize — what the
  // model actually sees.
  // Full-resolution HDR gain-map split. Both selectors point at the packed
  // R32G32B32A32_FLOAT texture; RGB is SDR base, A is the linear HDR/carrier multiplier.
  ID3D12Resource* packed_hdr_sdr = nullptr;
  ID3D12Resource* packed_hdr_gain = nullptr;
  unsigned int packed_width = 0;
  unsigned int packed_height = 0;

  ID3D12Resource* prepared_input = nullptr;
  unsigned int prepared_input_width = 0;
  // Full-resolution local SDR exposure scale used by HDR diagnostics.
  ID3D12Resource* effective_exposure_map = nullptr;
  unsigned int effective_exposure_width = 0;
  unsigned int effective_exposure_height = 0;
  unsigned int prepared_input_height = 0;

  // Model input as it was right before the Input Grade was applied. The
  // prepared input is graded in place, so this is a snapshot taken by the
  // grade step; it is null when no snapshot was captured this frame.
  ID3D12Resource* pre_grade_input = nullptr;
  unsigned int pre_grade_input_width = 0;
  unsigned int pre_grade_input_height = 0;

  // Model output as returned by NGX, before the Output Grade. The grade is
  // applied in place, so the ungraded image is a snapshot taken by the grade
  // step; it is null when no snapshot was captured this frame.
  ID3D12Resource* pre_grade_output = nullptr;
  unsigned int pre_grade_output_width = 0;
  unsigned int pre_grade_output_height = 0;

  // Model output after the Output Grade (the live resource when the grade ran).
  ID3D12Resource* model_output = nullptr;
  unsigned int model_output_width = 0;
  unsigned int model_output_height = 0;
  bool rcas_enabled = false;
  float rcas_strength = 0.0f;
  GradeSettings input_grade = {};

  // Model output after composition (residual, strength, HDR remap).
  ID3D12Resource* composed_output = nullptr;
  unsigned int composed_output_width = 0;
  unsigned int composed_output_height = 0;

  // DLSS guides captured from the game.
  ID3D12Resource* motion = nullptr;
  unsigned int motion_width = 0;
  unsigned int motion_height = 0;

  ID3D12Resource* depth = nullptr;
  unsigned int depth_width = 0;
  unsigned int depth_height = 0;

  // Mask generated by the first successful Pre/Post-DLSS evaluation this frame.
  ID3D12Resource* importance_mask = nullptr;
  unsigned int importance_width = 0;
  unsigned int importance_height = 0;

  // Motion-reprojected temporal edit and its validation state. These are
  // exposed only on frames where both resources were produced successfully.
  ID3D12Resource* temporal_candidate = nullptr;
  ID3D12Resource* temporal_validated_candidate = nullptr;
  unsigned int temporal_width = 0;
  unsigned int temporal_height = 0;
  bool temporal_available = false;
};

// How the display shader should interpret the selected resource.
enum class DebugDisplayMode : uint32_t {
  Color = 0,   // pass through as RGB
  Motion = 1,  // remap [-1,1] xy to [0,1] and show as R=x, G=y
  Depth = 2,   // replicate the red channel
  Mask = 3,    // replicate the red channel (importance mask)
  PackedSdr = 4, // RGB from packed gain-map texture
  GainMap = 5,   // alpha mapped from [-4,6] for display
  HdrRoundtripDiagnostic = 6,
  HdrRoundtripError = 7,
  HdrLocalExposure = 8,
  GameExposure = 9,
  TemporalCandidateStatus = 10,
  TemporalValidationStatus = 11,
  TemporalEdit = 12,
};

struct DebugViewDef {
  const char* name;
  const char* tooltip;
  DebugDisplayMode display_mode;
  // Returns the selected resource and its content size. Returns nullptr if
  // the resource is unavailable this frame. The resource may be larger than
  // the content (e.g. NGX writes into the top-left corner of its output);
  // the display shader accounts for that.
  ID3D12Resource* (*select)(const DebugSnapshot& snapshot,
                            unsigned int* out_content_width,
                            unsigned int* out_content_height);
  // Set on views that need the ungraded model input: the pipeline then
  // snapshots the model input before the Input Grade runs. Views without it
  // observe what the pipeline already produced.
  bool needs_pre_grade_input = false;
  // Same, for the model output around the Output Grade.
  bool needs_pre_grade_output = false;
};

// The debug view table. Terminated by an entry whose `name` is nullptr;
// iterate until then. Adding or removing a view is a single-line edit here.
extern const DebugViewDef kDebugViews[];

// True when the selected debug view requires the pre-grade model-input
// snapshot. Used by the grade step to know when to capture it.
bool DebugViewNeedsPreGradeInput(int debug_view);

// Same, for the pre-grade model-output snapshot.
bool DebugViewNeedsPreGradeOutput(int debug_view);

// Renders the selected debug view into `target`, which the caller owns and
// must have sized to `target_width × target_height`. `debug_view` follows
// the settings convention: 0 = off, N = kDebugViews[N-1].
// Returns true on success.
bool RenderDebugView(
    CommandContext& state,
    ComputeEngine& codec,
    ID3D12GraphicsCommandList* command_list,
    const DebugSnapshot& snapshot,
    const model_pipeline::HdrUniforms* hdr,
    int debug_view,
    ID3D12Resource* target,
    unsigned int target_width,
    unsigned int target_height);

}  // namespace reshade_dlssnr
